#!/usr/bin/env python3
"""Copy the Arena Levante / Orriols shape formulas (BUILDINGS, MAT, helpers) from the arena-levante-voxels
viewer into lev-shapes.js, with the OpenStreetMap site data inlined (footprints, pitches, neighbourhood blocks;
the satellite ground photo is left out). Sets window.LEV = { BUILDINGS, MAT, HELPERS, SITE }.

Usage:  python3 tools/sync-lev.py [path/to/arena-levante-voxels]
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '..', 'voxel-maps', 'arena-levante-voxels')
OUT = os.path.join(ROOT, 'lev-shapes.js')

html = open(os.path.join(SRC, 'index.html'), encoding='utf-8').read()
m = re.search(r'<script>\n(\(function \(\) \{.*?window\.LEV = .*?\}\)\(\);)\s*</script>', html, re.S)
if not m:
    sys.exit('SHAPES block not found in ' + SRC)
block = m.group(1)
raw = open(os.path.join(SRC, 'site-data.js'), encoding='utf-8').read()
site = json.loads(raw[raw.index('{'):raw.rindex('}') + 1])
site.pop('ground', None)                                      # satellite photo: viewer only
needle = 'const SITE = window.LEV_SITE;'
if needle not in block:
    sys.exit('expected "' + needle + '" in the SHAPES block')
block = block.replace(needle, 'const SITE = /*SITE-DATA*/' + json.dumps(site, separators=(',', ':')) + '/*END-SITE-DATA*/;', 1)
head = ('// Estadi Ciutat de València (Levante UD), Arena and Orriols as implicit formulas f(u, v, z, T) -> material id.\n'
        '// GENERATED by tools/sync-lev.py from the arena-levante-voxels viewer - edit the source there, not here.\n'
        '// Footprints, pitches and neighbourhood blocks: (c) OpenStreetMap contributors, ODbL.\n')
open(OUT, 'w', encoding='utf-8').write(head + block + '\n')
print(f'wrote {OUT} ({os.path.getsize(OUT) / 1024:.1f} KB)')
