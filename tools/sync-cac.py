#!/usr/bin/env python3
"""Copy the Calatrava shape formulas (BUILDINGS, MAT, helpers, SITE footprints) from the
calatrava-voxels viewer into cac-shapes.js, so the dashboard can voxelise the same buildings.

Usage:  python3 tools/sync-cac.py [path/to/calatrava-voxels/index.html]
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '..', 'voxel-maps', 'calatrava-voxels', 'index.html')
OUT = os.path.join(ROOT, 'cac-shapes.js')

html = open(SRC, encoding='utf-8').read()
m = re.search(r'<script>\n(\(function \(\) \{.*?window\.CAC = .*?\}\)\(\);)\s*</script>', html, re.S)
if not m:
    sys.exit('SHAPES block not found in ' + SRC)
head = ('// Ciutat de les Arts i les Ciències (Valencia) as implicit formulas f(u, v, z, T) -> material id.\n'
        '// GENERATED by tools/sync-cac.py from the calatrava-voxels viewer - edit the source there, not here.\n'
        '// Footprints / pools: (c) OpenStreetMap contributors, ODbL.\n')
open(OUT, 'w', encoding='utf-8').write(head + m.group(1) + '\n')
print(f'wrote {OUT} ({os.path.getsize(OUT) / 1024:.1f} KB)')
